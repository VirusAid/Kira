/** Указатели обхода круга — по одному на набор формулировок. */
const cursor = new Map<string, number>()

/**
 * С какого места начинается обход в этой сессии.
 *
 * Без него обход всегда стартовал бы с первого варианта, а первый вариант — это
 * исходная фраза. Kira живёт короткими сессиями и перезапускается, так что
 * человек снова и снова слышал бы ровно ту же сухую строку, что и раньше, — вся
 * работа была бы не слышна. Сдвиг на сессию делает разными и первые ответы.
 */
let sessionShift = Math.floor(Math.random() * 6)

/** Обстановка, в которой произносится ответ. */
export interface ReplyContext {
  /** Подряд идущие команды за короткое время. */
  streak: number
  hour: number
  /** Первое обращение после долгого перерыва — можно поздороваться. */
  firstInAWhile: boolean
}

/**
 * Команд подряд, после которых человеку явно не до разговоров.
 *
 * Считаются только идущие ВПЛОТНУЮ: пять дел за пять минут — обычный рабочий
 * темп, а не спешка, и обрывать себя на нём было бы преждевременно. А вот пять
 * команд подряд без паузы — это уже очередь, и человек в ней работает.
 */
const STREAK_QUIET = 5
/** Пауза, после которой команда считается новой, а не продолжением очереди. */
const STREAK_GAP_MS = 60_000
/** Перерыв, после которого человек возвращается, а не продолжает. */
const AWAY_MS = 4 * 60 * 60_000

let lastAt = 0
let streak = 0

/** Текущая обстановка: считается сама по ритму обращений. */
function context(now: number): ReplyContext {
  const gap = now - lastAt
  streak = gap < STREAK_GAP_MS ? streak + 1 : 1
  // lastAt === 0 — Kira только запустилась: это тоже встреча после перерыва
  const firstInAWhile = lastAt === 0 || gap > AWAY_MS
  lastAt = now
  return { streak, hour: new Date(now).getHours(), firstInAWhile }
}

/**
 * Приветствие при встрече после перерыва.
 *
 * Ровно один раз на возвращение и только у характеров, которым здороваться
 * свойственно: у «деловой» это лишний шум, а вручную написанный характер мы не
 * знаем — навязывать ему манеру нельзя.
 */
function greeting(hour: number, tone: Tone): string {
  const утро = hour >= 5 && hour < 12
  const вечер = hour >= 18 && hour < 24
  switch (tone) {
    case 'тёплый': return утро ? 'Доброе утро. ' : вечер ? 'Добрый вечер. ' : 'С возвращением. '
    case 'озорной': return утро ? 'Утро доброе. ' : вечер ? 'Вечер добрый. ' : 'О, привет. '
    case 'учтивый': return утро ? 'Доброе утро. ' : вечер ? 'Добрый вечер. ' : 'Рада снова быть полезной. '
    default: return ''
  }
}

/** Длиннее этого фраза уже самодостаточна — приветствие сделает её громоздкой. */
const GREETING_MAX = 30

/** Сбросить ритм и обход круга — для тестов и перезапуска сессии. */
export function resetPersonaState(): void {
  cursor.clear()
  sessionShift = 0 // тестам нужен предсказуемый порядок
  lastAt = 0
  streak = 0
}

/** Варианты для регистра с откатом на «обычный», иначе — исходная фраза. */
function variantsFor(set: VariantSet, tone: Tone, base: string): string[] {
  if (tone === 'сухой') return [base]
  return set[tone] ?? set['обычный'] ?? [base]
}

/**
 * Живая формулировка того же подтверждения.
 *
 * Чистая функция от базовой фразы, характера и обстановки — состояние (обход
 * круга) вынесено в `key`, чтобы поведение было предсказуемым и проверяемым.
 */
export function pickReply(base: string, tone: Tone, ctx: ReplyContext): string {
  const text = base.trim()
  if (!text || tone === 'сухой') return base

  // целая фраза
  let set = PHRASES[text]
  let tail = ''
  if (!set) {
    // глагол с продолжением: «Открываю корзину» — меняем только глагол
    const space = text.indexOf(' ')
    const verb = space === -1 ? text : text.slice(0, space)
    const verbSet = VERBS[verb]
    if (!verbSet) return base // незнакомая фраза остаётся собой — это безопасно
    tail = space === -1 ? '' : text.slice(space)
    // с дополнением годятся только глагольные варианты, иначе выйдет
    // «Момент корзину»
    set = tail ? verbSet.сГлаголом : (verbSet.безДополнения ?? verbSet.сГлаголом)
  }

  let options = variantsFor(set, tone, text)
  // Человек гонит команды очередью — сейчас он работает, а не общается.
  // Оставляем самое короткое: болтовня в этот момент мешает.
  if (ctx.streak >= STREAK_QUIET) {
    const shortest = options.reduce((a, b) => (b.length < a.length ? b : a))
    return shortest + tail
  }

  const key = `${text}|${tone}`
  const i = (cursor.get(key) ?? sessionShift - 1) + 1
  cursor.set(key, i)
  options = options.length ? options : [text]
  const phrase = options[i % options.length] + tail
  const hello = ctx.firstInAWhile && phrase.length <= GREETING_MAX ? greeting(ctx.hour, tone) : ''
  return hello + phrase
}

/**
 * Есть ли у фразы живые варианты. Нужно тестам: таблица привязана к фразам
 * действий по тексту, и разойтись они могут молча — характер просто перестанет
 * звучать, и никто этого не заметит.
 */
export function hasVariants(base: string): boolean {
  const text = base.trim()
  if (PHRASES[text]) return true
  const space = text.indexOf(' ')
  return !!VERBS[space === -1 ? text : text.slice(0, space)]
}

/**
 * Подтверждение действия голосом Kira — с её характером и с оглядкой на то,
 * что происходит вокруг.
 */
export function livelyReply(base: string): string {
  try {
    return pickReply(base, toneOf(getSettings().personality), context(Date.now()))
  } catch {
    return base // характер — украшение; сломаться из-за него ответ не должен
  }
}
