/**
 * MCP — контракт слоя расширений.
 *
 * MCP (Model Context Protocol) — стандартный способ для программ отдавать наружу
 * свои возможности. Для Kira это НЕ «инструменты для нейросети», а просто ещё
 * один источник действий: решение о вызове принимает ядро, а модель нужна лишь
 * там, где ядро не поняло фразу. Поэтому команда к MCP-серверу остаётся такой же
 * быстрой и предсказуемой, как встроенная.
 *
 * Контракт намеренно не зависит от конкретного SDK и транспорта: stdio, HTTP и
 * сама Kira реализуют один и тот же интерфейс. Из этого следуют два решения,
 * которые легко нарушить и потом дорого чинить:
 *
 *  • ОПИСАНИЕ ИНСТРУМЕНТА — чистые данные, без методов. Список инструментов
 *    кэшируется, показывается в интерфейсе и хранится в привязках, которые
 *    переживают перезапуск, — а сервер в этот момент может быть выключен. Вызов
 *    живёт на провайдере (`call`), как и в самом протоколе, где tools/list и
 *    tools/call — разные методы сервера.
 *
 *  • НАРУЖУ УХОДИТ ExecResult, а не сырой ответ MCP. Ни `content[0].text`, ни
 *    `isError` не должны встречаться выше этого слоя: ровно на таком смешении
 *    статуса и содержимого ядро уже дважды ловило баги.
 */
import type { ExecResult } from '../../core/types'
import type { McpBinding, McpServerConfig, McpStatus, McpTool } from '../../../shared/types'

// Описания сервера, инструмента, состояния и привязки — ОБЩИЙ контракт: их
// показывает интерфейс, поэтому они живут в shared, а не в main. Здесь остаётся
// только то, что относится к исполнению.
export type { McpBinding, McpServerConfig, McpStatus, McpTool }

/** Версия протокола, с которой Kira представляется серверам. */
export const PROTOCOL_VERSION = '2025-06-18'

/**
 * Контекст вызова. Отдельным объектом, чтобы позже добавить трассировку,
 * прогресс или журналирование, не трогая сигнатуру у всех транспортов.
 */
export interface CallContext {
  signal?: AbortSignal
  timeoutMs?: number
}

/** Отписка — возвращается подписками, чтобы не плодить `removeListener`. */
export type Disposable = () => void

/**
 * Живое подключение к серверу. Создаётся из McpServerConfig и считается
 * одноразовым: упал процесс — уничтожаем и создаём заново из той же настройки,
 * не трогая остальную систему.
 */
export interface McpProvider {
  readonly config: McpServerConfig
  status(): McpStatus
  connect(): Promise<void>
  disconnect(): Promise<void>
  listTools(): Promise<McpTool[]>
  call(tool: string, args: Record<string, unknown>, ctx?: CallContext): Promise<ExecResult>
  /** Сервер сообщил, что список инструментов изменился. */
  onToolsChanged(cb: () => void): Disposable
}
