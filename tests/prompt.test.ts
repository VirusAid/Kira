/**
 * Системный промпт: то, от чего зависит скорость ответа и поведение Kira.
 *
 * Проверяем не текст (он живой и меняется), а СВОЙСТВА, которые легко
 * потерять случайной правкой:
 *
 * 1) изменчивое стоит в конце. Движки кэшируют обработанный НАЧАЛЬНЫЙ кусок
 *    промпта, и один изменившийся символ обесценивает всё, что после него.
 *    Когда метка времени с минутами стояла пятой строкой, каждую минуту
 *    пересчитывались одиннадцать тысяч символов — тестировщик жаловался, что
 *    Kira долго думает даже с локальной моделью;
 * 2) время без минут — иначе префикс ломается ежеминутно;
 * 3) правило про локальный рабочий стол на месте: без него Kira отвечает как
 *    чат-бот, «вы можете открыть это сами».
 */
import { buildSystemPrompt } from '../src/main/modules/ai/kira'

let pass = 0, fail = 0
const t = (n: string, ok: boolean, extra = ''): void => {
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${extra ? '  ' + extra : ''}`); ok ? pass++ : fail++
}

/*
 * Начала изменчивых блоков — ровно те строки, которыми они начинаются в
 * kira.ts. Держим списком в одном месте: добавится новый изменчивый блок —
 * сюда же, иначе тест начнёт ложно ругаться на него как на «затесавшийся».
 */
const VOLATILE = /^(Память о пользователе|ЧТО ТЫ УЖЕ СДЕЛАЛА|Сейчас:|\[ЭКРАН ПОЛЬЗОВАТЕЛЯ СЕЙЧАС\])/

function main(): void {
  const prompt = buildSystemPrompt({ withTools: true })
  const parts = prompt.split('\n\n')

  // ── изменчивое — в хвосте ─────────────────────────────────────────────────
  const timeAt = parts.findIndex((p) => /Сейчас:/.test(p))
  t('метка времени присутствует', timeAt !== -1)
  const after = parts.slice(timeAt + 1).join('\n\n').length
  t('после метки времени почти ничего не пересчитывается', after < 500,
    `-> символов после неё: ${after}`)

  const stable = parts.slice(0, timeAt).join('\n\n').length
  t('постоянная часть — подавляющее большинство промпта',
    stable > prompt.length * 0.9, `-> ${Math.round(stable * 100 / prompt.length)}%`)

  // ── время без минут ───────────────────────────────────────────────────────
  const timeBlock = parts[timeAt] ?? ''
  t('время огрублено до получаса (иначе префикс ломается каждую минуту)',
    /около \d{1,2}:(00|30)/.test(timeBlock), `-> ${timeBlock.trim().slice(0, 60)}`)

  // ── руководство по управлению компьютером не потерялось ───────────────────
  t('руководство по инструментам на месте', /Управление ПК/.test(prompt))
  t('без инструментов оно исчезает',
    !/Управление ПК/.test(buildSystemPrompt({ withTools: false })))

  // ── действия локальные, а не советы ───────────────────────────────────────
  t('сказано, что Kira работает на компьютере пользователя',
    /НА КОМПЬЮТЕРЕ ПОЛЬЗОВАТЕЛЯ/.test(prompt))
  t('запрещено советовать вместо действия', /Никогда не отвечай «вы можете открыть/.test(prompt))
  /*
   * Правило должно замыкать ПОСТОЯННУЮ часть — то есть стоять после всего
   * неизменного и перед всем изменчивым.
   *
   * Проверяем именно это, а не «предпоследний абзац»: изменчивых блоков может
   * не быть вовсе (пустая память у нового пользователя) или быть несколько
   * (память, поступки, экран), и привязка к позиции ложно падала бы в полном
   * прогоне, где база уже наполнена другими тестами.
   */
  const localityAt = parts.findIndex((p) => /ГДЕ ТЫ РАБОТАЕШЬ/.test(p))
  const firstVolatile = parts.findIndex((p) => VOLATILE.test(p))
  t('правило про локальность замыкает постоянную часть',
    localityAt !== -1 && localityAt < firstVolatile,
    `-> правило ${localityAt}, первый изменчивый ${firstVolatile}`)
  const strays = parts.slice(localityAt + 1).filter((p) => p.trim() && !VOLATILE.test(p))
  t('после правила идёт ТОЛЬКО изменчивое', strays.length === 0,
    strays.length ? `-> затесалось: ${strays[0].slice(0, 50)}` : '')

  // ── краткость ─────────────────────────────────────────────────────────────
  t('задана длина ответа', /ДЛИНА ОТВЕТА: одна-две фразы/.test(prompt))
  t('план — только для сложного', /План проговаривай ТОЛЬКО/.test(prompt))

  // ── путь к папкам не угадывается ──────────────────────────────────────────
  t('системные папки переданы явно', /СИСТЕМНЫЕ ПАПКИ/.test(prompt))

  console.log(`\n=== ИТОГО: ${pass} PASS, ${fail} FAIL ===`)
  process.exit(fail ? 1 : 0)
}
main()
