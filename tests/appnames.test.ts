/**
 * Сведение написания имён программ.
 *
 * Таблица приложений сверялась точным совпадением, и «телеграмм» с двумя «м»
 * давало «не нашла программу» — при том что «телеграм» в таблице был.
 *
 * Отдельно проверяем, что сведение не СКЛЕИВАЕТ разные программы. Первая же
 * попытка написать его содержала `/(.)+/` вместо `/(.)\1+/` — без обратной
 * ссылки выражение сминает всю строку в последнюю букву, и «телеграм» со
 * «стимом» становились одним и тем же. Проверки ниже ловят именно это.
 */
import { normalizeAppName as norm } from '../src/main/modules/system'

let pass = 0, fail = 0
const t = (n: string, ok: boolean, extra = ''): void => {
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${extra ? '  ' + extra : ''}`); ok ? pass++ : fail++
}

function main(): void {
  // ── написания одной программы сходятся ────────────────────────────────────
  const tg = norm('телеграм')
  for (const v of ['телеграмм', 'Телеграмм', 'ТЕЛЕГРАММ', 'теле грам', 'теле-грам', 'телеграм ']) {
    t(`«${v}» сводится к «телеграм»`, norm(v) === tg, `-> ${norm(v)}`)
  }

  // ── разные программы НЕ склеиваются ───────────────────────────────────────
  const names = ['телеграм', 'стим', 'дискорд', 'хром', 'блокнот', 'калькулятор']
  const collapsed = names.map(norm)
  t('разные программы остаются разными', new Set(collapsed).size === names.length,
    `-> ${collapsed.join(', ')}`)
  t('сведение не съедает строку до одной буквы',
    collapsed.every((c) => c.length > 2), `-> ${collapsed.join(', ')}`)

  // ── что именно убирается ──────────────────────────────────────────────────
  t('регистр не важен', norm('SteAM') === norm('steam'))
  t('пробелы и дефисы убираются', norm('ад обе акробат') === norm('адобе-акробат'))
  t('повтор буквы схлопывается', norm('ааабв') === 'абв', `-> ${norm('ааабв')}`)
  t('одиночные буквы не трогаются', norm('абв') === 'абв')

  console.log(`\n=== ИТОГО: ${pass} PASS, ${fail} FAIL ===`)
  process.exit(fail ? 1 : 0)
}
main()
